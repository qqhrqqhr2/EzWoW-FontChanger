# Lists every .ttf/.otf in this folder for EzWoW - Font Changer (no renaming needed).
# Put this file in Interface\AddOns\EzWoW-MyFonts\, right-click > Run with PowerShell,
# then restart the game. Run it again whenever you add or remove fonts.
$folder = Split-Path -Parent $MyInvocation.MyCommand.Path
$fonts = Get-ChildItem -LiteralPath $folder -File | Where-Object { $_.Extension -match '^\.(ttf|otf)$' } | Sort-Object Name
$lines = $fonts | ForEach-Object { '    "' + ($_.Name -replace '\\', '\\' -replace '"', '\"') + '",' }
$lua = "-- Generated by make_myfonts.ps1 - run it again after changing fonts`nEzWoW_MyFonts = {`n" + ($lines -join "`n") + "`n}`n"
$utf8 = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText((Join-Path $folder 'MyFonts.lua'), $lua, $utf8)
$toc = "## Interface: 16001`n## Title: EzWoW - My Fonts`n## Notes: Your own font files for EzWoW - Font Changer (generated)`n## Category: EzWoW`n`nMyFonts.lua`n"
[System.IO.File]::WriteAllText((Join-Path $folder 'EzWoW-MyFonts.toc'), $toc, $utf8)
Write-Host "$($fonts.Count) font(s) listed:"
$fonts | ForEach-Object { Write-Host "  $($_.Name)" }
Read-Host "Done. Restart the game. Press Enter to close"
