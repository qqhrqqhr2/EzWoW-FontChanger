"""Make every font in your EzWoW-MyFonts folder show up in EzWoW - Font Changer
with its real file name (no need to rename to font1.ttf ...).

WoW addons can't list a folder, so this writes a tiny addon into the folder
that tells Font Changer which files are there:
    EzWoW-MyFonts/EzWoW-MyFonts.toc
    EzWoW-MyFonts/MyFonts.lua

Usage (run again after adding or removing fonts, then restart the game):
    python make_myfonts.py "C:\\Program Files (x86)\\World of Warcraft\\_classic_\\Interface\\AddOns\\EzWoW-MyFonts"
"""
import sys
from pathlib import Path

folder = Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
fonts = sorted(p.name for p in folder.iterdir() if p.suffix.lower() in (".ttf", ".otf"))
lua_names = ",\n".join('    "%s"' % name.replace("\\", "\\\\").replace('"', '\\"') for name in fonts)
(folder / "MyFonts.lua").write_text(
    "-- Generated by EzWoW Font Changer tools/make_myfonts.py - run it again after changing fonts\n"
    "EzWoW_MyFonts = {\n" + lua_names + ("\n" if fonts else "") + "}\n", encoding="utf-8")
(folder / "EzWoW-MyFonts.toc").write_text(
    "## Interface: 16001\n## Title: EzWoW - My Fonts\n"
    "## Notes: Your own font files for EzWoW - Font Changer (generated)\n"
    "## Category: EzWoW\n\nMyFonts.lua\n", encoding="utf-8")
print(f"{len(fonts)} font(s) listed in {folder}")
for name in fonts:
    print("  ", name)
